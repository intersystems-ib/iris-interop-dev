//! #534 — reading an ObjectScript error frame without guessing which KIND of frame it is.
//!
//! An IRIS runtime error names the INT routine it trapped in, never the source:
//! `<UNDEFINED>LIST+2^OMORDL`. Two different things wear that shape.
//!
//! * `Pkg.Class.N` is an INT routine the CLASS compiler generated. Its method labels are
//!   generated too, each with a `z` prefix, so `zSlotKey` is the method `SlotKey`.
//! * `OMORDL` is a routine's own INT. Its labels are the ones the author typed — `zINIT`
//!   among them, where `z` is the first letter of the name and not a prefix at all — and
//!   there is no class of that name anywhere.
//!
//! Before #534 `iris_debug(action=map_int)` knew only the first. It looked EVERY frame up in
//! `%Dictionary.CompiledClass` and answered `ROUTINE_NOT_FOUND` — *"'OMORDL' is not a
//! compiled class"* — for the commonest frame in routine-based code. That sentence is true
//! and it is about a question nobody asked: a failed lookup served as a negative fact about
//! the world, which is this repo's commonest bug shape.
//!
//! ## What is decidable here, and what is not
//!
//! Everything in this module is a pure function of the frame string and of `.INT` TEXT THE
//! CALLER SUPPLIES. That is deliberate: it is the half that can be proved without an IRIS
//! instance, and the fetch is the seam. Specifically NOT here:
//!
//! * fetching the `.INT` over Atelier — [`INT_SOURCE_REQUIRED`] says so to the caller and
//!   names the `iris_doc` call that gets the text, rather than inventing a line;
//! * mapping an INT line back to a `.MAC` line. Measured on a live 2026.2 stack and recorded
//!   in #534's thread: `OMSTOCK.mac` has 28 lines and its `.int` 26, because the `.int` drops
//!   blank lines. So a MAC line number computed by counting `.int` lines is off by one for
//!   every blank line above the target — plausible, close and wrong, which is worse than a
//!   refusal. The INT line this module returns is exact, and it is reported AS an INT line.

use crate::tools::info::IntFrame;
use rmcp::{model::CallToolResult, ErrorData as McpError};

// ── the outcome names ────────────────────────────────────────────────────────────────────────
//
// Declared as consts rather than inlined at the call site because `every_refusal_names_a_remedy`
// reads this idiom (#418) — so none of these can reach a caller without a reviewed remedy on
// record.

/// The frame's label is not a label of the text supplied. Nothing was counted.
pub const INT_LABEL_NOT_FOUND: &str = "INT_LABEL_NOT_FOUND";
/// `LABEL+n` where the block under `LABEL` is shorter than `n`. No line is guessed.
pub const INT_OFFSET_PAST_LABEL_BLOCK: &str = "INT_OFFSET_PAST_LABEL_BLOCK";
/// A negative offset, which no IRIS frame emits.
pub const INT_OFFSET_INVALID: &str = "INT_OFFSET_INVALID";
/// The supplied text is not an `.INT` listing — blank, or with no label at a line start.
pub const INT_SOURCE_UNUSABLE: &str = "INT_SOURCE_UNUSABLE";
/// A routine frame, decomposed, with no `.INT` text to count against. Not an absent routine.
pub const INT_SOURCE_REQUIRED: &str = "INT_SOURCE_REQUIRED";

/// Which kind of INT routine a frame's `^NAME` part names.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FrameKind {
    /// `Pkg.Class.N` — generated by the class compiler, so `z` is a label prefix.
    Class,
    /// `OMORDL` — a routine's own INT, so every label is the author's.
    Routine,
}

impl FrameKind {
    pub fn as_str(self) -> &'static str {
        match self {
            FrameKind::Class => "class",
            FrameKind::Routine => "routine",
        }
    }
}

/// `Some(class)` when `routine` is the INT routine a CLASS compiles to — `Pkg.Class.N`, whose
/// last dot-piece is the INT suffix and nothing else.
///
/// The ONE place that decides this. `parse_int_frame` derives the class name from it and
/// [`classify_routine`] derives the kind from it, so "which name is the class" and "is this a
/// class frame at all" cannot come to different answers — two sibling sites recognising
/// different sets is how the `z` rule came to be applied to routines in the first place.
pub fn class_of_int_routine(routine: &str) -> Option<&str> {
    match routine.rsplit_once('.') {
        Some((head, tail))
            if !head.is_empty() && !tail.is_empty() && tail.chars().all(|c| c.is_ascii_digit()) =>
        {
            Some(head)
        }
        _ => None,
    }
}

/// Classify a frame by its routine reference alone — no lookup, no connection, no I/O.
pub fn classify_routine(routine: &str) -> FrameKind {
    if class_of_int_routine(routine).is_some() {
        FrameKind::Class
    } else {
        FrameKind::Routine
    }
}

/// The routine reference at the head of `raw`, with IRIS's trailing error detail removed.
///
/// `<UNDEFINED>` appends the offending reference to the frame, and `<PROPERTY DOES NOT EXIST>`
/// appends the property and its class. Measured on a live 2026.2 stack (#534's thread):
/// `<UNDEFINED>F2+1^OMCUSTL *X` was looked up as `OMCUSTL *X`, a name nothing could ever
/// match — so fixing the classification alone would still have looked up a name with a space
/// in it.
///
/// `unittest_result::extract_frame` has always terminated the name this way; this is that rule,
/// as a function, for the second site that needed it.
pub fn routine_reference(raw: &str) -> &str {
    let raw = raw.trim_start();
    let end = raw
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '%'))
        .unwrap_or(raw.len());
    raw[..end].trim_end_matches('.')
}

/// One line of an `.INT` listing, with its 1-based number.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IntLine {
    pub line_number: usize,
    pub text: String,
}

/// The outcome of `LABEL+offset` arithmetic against `.INT` text.
///
/// FIVE outcomes, four of them refusals, because the thing that must never happen is a line
/// number the caller cannot tell apart from a counted one. "No line" has four distinct causes
/// here and each has its own remedy.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IntLineOutcome {
    /// Counted. `line_number` is exact AS AN INT LINE — see the module note on `.MAC`.
    Resolved {
        label_line: usize,
        block_lines: usize,
        line: IntLine,
    },
    /// The text is not an `.INT` listing, so nothing was searched. NOT "label not found".
    SourceUnusable { reason: &'static str },
    /// The label is absent from a listing that does have labels. `labels_present` is every
    /// label the text does contain, so the caller can see it fetched the wrong document.
    LabelNotFound {
        label: String,
        labels_present: Vec<String>,
    },
    /// The offset runs past the last line of the label's block. No neighbour is guessed.
    OffsetPastLabelBlock {
        label: String,
        offset: i64,
        label_line: usize,
        block_lines: usize,
    },
    /// A negative offset. No IRIS frame emits one, so the input is malformed.
    OffsetInvalid { offset: i64 },
}

impl IntLineOutcome {
    /// `None` for [`IntLineOutcome::Resolved`] — the only outcome that is not a refusal.
    pub fn code(&self) -> Option<&'static str> {
        match self {
            IntLineOutcome::Resolved { .. } => None,
            IntLineOutcome::SourceUnusable { .. } => Some(INT_SOURCE_UNUSABLE),
            IntLineOutcome::LabelNotFound { .. } => Some(INT_LABEL_NOT_FOUND),
            IntLineOutcome::OffsetPastLabelBlock { .. } => Some(INT_OFFSET_PAST_LABEL_BLOCK),
            IntLineOutcome::OffsetInvalid { .. } => Some(INT_OFFSET_INVALID),
        }
    }
}

/// Every label of an `.INT` listing, as `(1-based line number, label)`.
///
/// A label occupies the start of its line; generated and hand-written code alike indent
/// everything else. A `}` at column 0 closes a generated method body and is not a label, nor
/// is a `;` comment or a blank line — so the test is that the first character IS a label
/// character, which is positive rather than a list of things to skip.
pub fn int_labels(int_text: &str) -> Vec<(usize, String)> {
    int_text
        .lines()
        .enumerate()
        .filter_map(|(i, line)| label_of_line(line).map(|l| (i + 1, l.to_string())))
        .collect()
}

/// `Some(label)` when `line` starts a label block.
pub fn label_of_line(line: &str) -> Option<&str> {
    let first = line.chars().next()?;
    if !(first.is_ascii_alphanumeric() || first == '%' || first == '_') {
        return None;
    }
    let end = line
        .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_' || c == '%'))
        .unwrap_or(line.len());
    Some(&line[..end])
}

/// `LABEL+offset` against `.INT` text, counting the lines of that text exactly as given.
///
/// Offset 0 IS the label line: `LABEL^RTN` with no `+n` trapped on the label line itself.
///
/// Lines are counted literally, blank ones included. The `.int` IRIS stores has none (#534's
/// thread measured a 28-line `.mac` compiling to a 26-line `.int`), so skipping them would be
/// a correction with nothing to correct, applied to text this function cannot validate.
///
/// Precedence when more than one refusal applies: a malformed offset first (it is a fact about
/// the frame, true whatever text arrives), then unusable text, then the label, then the block
/// size. Each refusal names only what it actually checked.
pub fn map_label_offset(int_text: &str, label: &str, offset: i64) -> IntLineOutcome {
    if offset < 0 {
        return IntLineOutcome::OffsetInvalid { offset };
    }
    if int_text.trim().is_empty() {
        return IntLineOutcome::SourceUnusable {
            reason: "the int_source text is empty or all whitespace, so nothing was searched",
        };
    }
    let labels = int_labels(int_text);
    if labels.is_empty() {
        return IntLineOutcome::SourceUnusable {
            reason: "no line of the int_source text starts with a label, so it is not an .INT \
                     listing and nothing was searched",
        };
    }
    let lines: Vec<&str> = int_text.lines().collect();
    let Some(at) = labels.iter().position(|(_, name)| name == label) else {
        return IntLineOutcome::LabelNotFound {
            label: label.to_string(),
            labels_present: labels.into_iter().map(|(_, name)| name).collect(),
        };
    };
    let label_line = labels[at].0;
    // The block runs to the line before the next label, or to the end of the routine.
    let block_end = labels.get(at + 1).map_or(lines.len(), |(l, _)| l - 1);
    let block_lines = block_end + 1 - label_line;
    let target = label_line + offset as usize;
    if target > block_end {
        return IntLineOutcome::OffsetPastLabelBlock {
            label: label.to_string(),
            offset,
            label_line,
            block_lines,
        };
    }
    IntLineOutcome::Resolved {
        label_line,
        block_lines,
        line: IntLine {
            line_number: target,
            text: lines[target - 1].to_string(),
        },
    }
}

/// How many labels a refusal lists before it stops, so a routine with thousands of them
/// cannot bury the refusal's own sentence.
const LABELS_LISTED: usize = 25;

/// `iris_debug(action=map_int)`'s whole answer for a frame whose `.INT` text is in hand, and
/// its answer for a routine frame when it is not.
///
/// Pure: everything it needs is an argument, so the shape of every outcome — including the two
/// refusals #534 asks for — is testable with fixture text and no instance.
pub fn map_int_answer(
    err: &str,
    frame: &IntFrame,
    int_source: Option<&str>,
) -> Result<CallToolResult, McpError> {
    let Some(text) = int_source else {
        return crate::tools::envelope::ok_json(serde_json::json!({
            "success": true,
            "error_string": err,
            "signal": frame.signal,
            "frame_kind": frame.kind.as_str(),
            "routine": frame.routine,
            "label": frame.label,
            "offset": frame.offset,
            "mapped_to_source_line": false,
            "outcome": INT_SOURCE_REQUIRED,
            "note": format!(
                "The frame names the ROUTINE '{rtn}', not a class, so the old \
                 '{rtn} is not a compiled class' answer was about the wrong question — nothing \
                 here says the routine is missing. This server does not fetch the .INT itself: \
                 read it with iris_doc(mode='get', name='{rtn}.int') and call map_int again \
                 with int_source set to that text, and the exact INT line for {label}+{offset} \
                 comes back. Counting it by hand works too: offset 0 is the {label} line \
                 itself.",
                rtn = frame.routine,
                label = frame.label,
                offset = frame.offset,
            ),
        }));
    };
    let outcome = map_label_offset(text, &frame.label, frame.offset);
    let common = serde_json::json!({
        "error_string": err,
        "signal": frame.signal,
        "frame_kind": frame.kind.as_str(),
        "routine": frame.routine,
        "label": frame.label,
        "offset": frame.offset,
    });
    match outcome {
        IntLineOutcome::Resolved {
            label_line,
            block_lines,
            line,
        } => {
            let mut obj = common;
            merge(
                &mut obj,
                serde_json::json!({
                    "success": true,
                    "int_line_number": line.line_number,
                    "int_line": line.text,
                    "label_line_number": label_line,
                    "label_block_lines": block_lines,
                    "mapped_to_source_line": false,
                    "note": "int_line_number counts the lines of the int_source text supplied, \
                             and offset 0 is the label line itself. It is an .INT line, NOT a \
                             .MAC or .cls line: the .int IRIS stores drops the blank lines of \
                             the .mac it was compiled from (measured: a 28-line .mac, a 26-line \
                             .int), so every blank line above the target shifts the source line \
                             by one and no source line is offered here.",
                }),
            );
            crate::tools::envelope::ok_json(obj)
        }
        ref refusal => {
            let code = refusal
                .code()
                .expect("every outcome but Resolved is a refusal and carries a code");
            let (msg, extra) = match refusal {
                IntLineOutcome::Resolved { .. } => unreachable!("matched by the arm above"),
                IntLineOutcome::SourceUnusable { reason } => (
                    format!("{reason}. The label '{}' was never looked for.", frame.label),
                    serde_json::json!({}),
                ),
                IntLineOutcome::LabelNotFound {
                    label,
                    labels_present,
                } => (
                    format!(
                        "'{label}' is not a label of the int_source text supplied, so no line \
                         was counted — and this says nothing about whether the routine \
                         '{}' exists.",
                        frame.routine
                    ),
                    serde_json::json!({
                        "labels_present": labels_present.iter().take(LABELS_LISTED).collect::<Vec<_>>(),
                        "labels_total": labels_present.len(),
                        "labels_listed": labels_present.len().min(LABELS_LISTED),
                    }),
                ),
                IntLineOutcome::OffsetPastLabelBlock {
                    label,
                    offset,
                    label_line,
                    block_lines,
                } => (
                    format!(
                        "'{label}' starts at line {label_line} of the int_source text and its \
                         block is {block_lines} line(s) long, so +{offset} runs past the end of \
                         it. No line is returned: the line {offset} past the label belongs to \
                         whatever follows the block, and reporting it would be a guess."
                    ),
                    serde_json::json!({
                        "label_line_number": label_line,
                        "label_block_lines": block_lines,
                        "highest_offset_in_block": block_lines - 1,
                    }),
                ),
                IntLineOutcome::OffsetInvalid { offset } => (
                    format!(
                        "offset {offset} is negative, so there is no line to count to. A frame \
                         is <SIGNAL>LABEL+N^ROUTINE, with N a count of lines past LABEL."
                    ),
                    serde_json::json!({}),
                ),
            };
            let mut obj = common;
            merge(&mut obj, extra);
            crate::tools::envelope::fail_with(code, &msg, obj)
        }
    }
}

/// Fold `extra`'s keys into `into`. Both are built by `json!` at the call sites above, so both
/// are objects; a non-object would silently drop its fields, which is why neither is built
/// anywhere else.
fn merge(into: &mut serde_json::Value, extra: serde_json::Value) {
    if let (Some(a), serde_json::Value::Object(b)) = (into.as_object_mut(), extra) {
        for (k, v) in b {
            a.insert(k, v);
        }
    }
}
